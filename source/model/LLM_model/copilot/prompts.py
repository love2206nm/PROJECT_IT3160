"""
Prompts and Evaluation Schemas for Copilot and Critic Agents.
Provides strict Pydantic structured output models and system instructions
for zero-hallucination career roadmap generation and multi-turn advising.
"""

from typing import Dict, Any, Optional
from pydantic import BaseModel, Field, ConfigDict


class CriticScores(BaseModel):
    """Granular multi-dimensional evaluation scores for roadmap quality."""
    feasibility: float = Field(
        ...,
        ge=0.0,
        le=10.0,
        description="Score 0.0-10.0 on whether the 30-60-90 day progression and workload are realistic"
    )
    grounding: float = Field(
        ...,
        ge=0.0,
        le=10.0,
        description="Score 0.0-10.0 on strict adherence to O*NET evidence and candidate skill gap"
    )
    hallucination_free: float = Field(
        ...,
        ge=0.0,
        le=10.0,
        description="Score 0.0-10.0 on absence of fictional certificates, invented technologies, or ungrounded claims"
    )

    model_config = ConfigDict(extra="ignore")


class CriticEvaluation(BaseModel):
    """Structured evaluation report produced by the Critic Evaluator LLM."""
    approved: bool = Field(
        ...,
        description="True if roadmap passes all criteria (all individual scores >= 7.0), False otherwise"
    )
    feedback: str = Field(
        ...,
        description="Actionable, specific feedback detailing what to fix if rejected, or confirmation if approved"
    )
    scores: CriticScores = Field(
        ...,
        description="Numerical scoring breakdown across feasibility, grounding, and hallucination check"
    )

    model_config = ConfigDict(extra="ignore")


class LLMSocSuggestion(BaseModel):
    """Semantic classification schema for matching candidate profile to O*NET occupation."""
    soc_code: str = Field(
        ...,
        description="Closest matching 6-digit O*NET SOC code (e.g., '15-1252.00' or '15-1252')"
    )
    soc_title: str = Field(
        ...,
        description="Official O*NET occupation title corresponding to the SOC code"
    )
    confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Confidence score in [0.0, 1.0] representing semantic alignment"
    )
    rationale: str = Field(
        default="",
        description="Brief justification connecting candidate experience and skills to this O*NET role"
    )

    model_config = ConfigDict(extra="ignore")


