from typing import Optional, List, Dict, Any
from pydantic import BaseModel, Field, ConfigDict

from source.domain.entities.candidate import CandidateProfile
from source.domain.entities.risk import RiskProfile
from source.domain.entities.transition import SafeTransitionRole, SkillGap
from source.domain.entities.roadmap import CopilotRoadmap


class AnalysisResult(BaseModel):
    """
    Thực thể kết quả hợp nhất (Unified Analysis Result) đại diện cho toàn bộ
    kết quả phân tích từ Use Case Service gửi về Controller/Presentation Layer.
    """
    session_id: Optional[str] = Field(
        default=None,
        description="Unique session/thread identifier for the analysis workflow"
    )
    candidate_profile: CandidateProfile = Field(
        ...,
        description="Extracted and confirmed candidate profile"
    )
    risk_profile: RiskProfile = Field(
        ...,
        description="Calculated or predicted AI career threat risk profile"
    )
    safe_pivots: List[SafeTransitionRole] = Field(
        default_factory=list,
        description="Top safe pivot recommendations computed by the clustering engine"
    )
    skill_gap: Optional[SkillGap] = Field(
        default=None,
        description="Detailed skill gap comparison between candidate and primary pivot target"
    )
    skill_gaps: List[SkillGap] = Field(
        default_factory=list,
        description="Detailed skill gaps comparison across all recommended safe pivot targets"
    )
    roadmap: Optional[CopilotRoadmap] = Field(
        default=None,
        description="Actionable 30-60-90 days career transition roadmap generated by Copilot"
    )
    critic_review: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Independent critic evaluation scores, feedback, and audit findings"
    )
    grounding_evidences: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="Top evidence excerpts retrieved from O*NET knowledge corpus via Hybrid RAG"
    )

    model_config = ConfigDict(
        populate_by_name=True,
        validate_assignment=True,
        extra="ignore"
    )
